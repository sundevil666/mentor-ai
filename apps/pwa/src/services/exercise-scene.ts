/** Generic visual vocabulary; never store personalized lesson text or IDs here. */
export type ExerciseScene = 'help' | 'check' | 'parcel' | 'door' | 'door-open' | 'window' | 'keys' | 'repair' | 'cafe' | 'wait' | 'relief' | 'explain' | 'traffic' | 'run' | 'phone' | 'tickets' | 'envelope' | 'leak' | 'luggage' | 'wallet' | 'weather' | 'car' | 'clothes' | 'cooking' | 'laptop' | 'map' | 'meeting' | 'conversation' | 'train' | 'walk';
export function resolveExerciseScene(prompt: string): ExerciseScene | null {
  const rules: Array<[RegExp, ExerciseScene]> = [
    [/беж|побеж|\brun\b|\bran\b/i, 'run'],
    [/откр.{0,12}двер|open.{0,12}door/i, 'door-open'],
    [/конверт|\benvelope\b/i, 'envelope'],
    [/теч[её]т|протеч|\bleak\b/i, 'leak'],
    [/чемодан|\bsuitcase\b|\bluggage\b/i, 'luggage'],
    [/кошел[её]к|\bwallet\b/i, 'wallet'],
    [/багажник|\bboot\b|\btrunk\b/i, 'car'],
    [/ремонт|почин|почини|\brepair\b|\bfixed\b|электрик|тормоз|заменил.{0,8}экран|\bbrakes\b/i, 'repair'],
    [/куртк|чистк|\bjacket\b|\blaundry\b/i, 'clothes'],
    [/готовил|готовить|\bcook(?:ing)?\b/i, 'cooking'],
    [/ноутбук|\blaptop\b/i, 'laptop'],
    [/автобус|\bbus\b/i, 'traffic'],
    [/поезд|вокзал|станци|\btrain\b|\bstation\b/i, 'train'],
    [/машин|отвез|забрать.{0,14}домой|\bcar\b|\bdrive\b|pick.{0,8}up/i, 'car'],
    [/пешком|ходил|\bwalk(?:ing)?\b/i, 'walk'],
    [/погод|снег|(?<![а-яё])дожд|\bweather\b|\bsnow\b|\brain\b/i, 'weather'],
    [/адрес|заблуд|\baddress\b|got(?:ten)? lost/i, 'map'],
    [/сумк|\bbag\b/i, 'luggage'],
    [/посыл|достав|package|parcel/i, 'parcel'],
    [/ключ|\bkeys\b/i, 'keys'],
    [/билет|tickets/i, 'tickets'],
    [/проб(?:к|ок)|traffic/i, 'traffic'],
    [/позвон|телефон|called|\bcall\b|\bphone\b/i, 'phone'],
    [/окно|окна|\bwindow\b/i, 'window'],
    [/кофе|кафе|счёт|счет|coffee|\bpay\b/i, 'cafe'],
    [/подож|жду|ждать|минут|hold on|\bwait\b|\bminute\b/i, 'wait'],
    [/встреч|подтверд.{0,12}врем|бронирован|\bmeeting\b|\bbooking\b/i, 'meeting'],
    [/отч[её]т|документ|\breport\b|\bdocument\b/i, 'check'],
    [/сообщени|ответ|сказал|\bmessage\b|\banswer\b|\brepl/i, 'conversation'],
    [/облегч|relieved/i, 'relief'],
    [/понима|объясн|understand|explaining/i, 'explain'],
    [/помо|попрос|could you|\bhelp\b/i, 'help'],
    [/провер|ошиб|план|\bcheck|mistake|\bplan\b/i, 'check'],
    [/шум|сосед|neighbour|\bnoise\b/i, 'door'],
  ];
  return rules.find(([pattern]) => pattern.test(prompt))?.[1] ?? null;
}
